export type AccountType = 'cash' | 'bank' | 'credit' | 'wallet' | 'other';
/** 'adjust' = manual balance correction: signed amount, not income or expense. */
export type TxnType = 'income' | 'expense' | 'transfer' | 'adjust';
export type Freq = 'once' | 'daily' | 'weekly' | 'monthly' | 'yearly';

export const ACCOUNT_TYPES: Record<AccountType, string> = {
  cash: 'Cash',
  bank: 'Bank',
  credit: 'Credit card',
  wallet: 'E-wallet',
  other: 'Other',
};

export const FREQS: Record<Freq, string> = { once: 'Once', daily: 'Daily', weekly: 'Weekly', monthly: 'Monthly', yearly: 'Yearly' };

export interface Account {
  id: string;
  name: string;
  type: AccountType;
  /** ISO 4217 code. Amounts on this account are in this currency. */
  currency: string;
  /** Integer minor units (cents). Negative for credit card debt. */
  openingBalance: number;
  archived: boolean;
}

export interface Category {
  id: string;
  name: string;
  kind: 'income' | 'expense';
  /** Monthly budget in base currency minor units (expense categories only). */
  budget?: number;
}

export interface Txn {
  id: string;
  /** YYYY-MM-DD */
  date: string;
  type: TxnType;
  /** Integer minor units in the source account's currency. > 0, except 'adjust' which is signed. */
  amount: number;
  accountId: string;
  /** Transfers only. */
  toAccountId?: string;
  /** Transfers between currencies: amount received, in the destination account's currency. */
  toAmount?: number;
  /** Income/expense only. */
  categoryId?: string;
  note?: string;
  /** Set on transactions generated by a recurring rule. */
  recurringId?: string;
}

export interface Recurring {
  id: string;
  freq: Freq;
  /** First occurrence, YYYY-MM-DD. Later ones are computed from it, so month-end dates don't drift. */
  start: string;
  /** Last date allowed, inclusive. */
  end?: string;
  /** Occurrences already posted or skipped (index of the next one). */
  posted: number;
  /** false = wait for the user to confirm each payment. Missing means true (rules created before this flag). */
  auto?: boolean;
  template: Omit<Txn, 'id' | 'date' | 'recurringId'>;
}

export interface Data {
  schemaVersion: 2;
  /** Base currency: totals, charts and budgets are shown in it. */
  currency: string;
  /** Value of 1 unit of a currency in base currency, e.g. { EUR: 1.08 } when base is USD. */
  rates: Record<string, number>;
  accounts: Account[];
  categories: Category[];
  txns: Txn[];
  recurring: Recurring[];
}

export interface Filter {
  from?: string;
  to?: string;
  accountIds?: string[];
  categoryIds?: string[];
  types?: TxnType[];
  search?: string;
}
